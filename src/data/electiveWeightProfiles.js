const WEIGHT_TOLERANCE = 0.0001;

function normalizeElectiveName(name = "") {
  return String(name).trim().replace(/\s+/g, " ").toLowerCase();
}

function sumWeights(weights = {}) {
  return Object.values(weights).reduce((sum, value) => sum + Number(value || 0), 0);
}

export function getElectiveWeightProfile(electiveName) {
  const normalizedName = normalizeElectiveName(electiveName);
  const matchedName = Object.keys(ELECTIVE_WEIGHT_PROFILES).find(
    (name) => normalizeElectiveName(name) === normalizedName
  );

  return matchedName ? ELECTIVE_WEIGHT_PROFILES[matchedName] : null;
}

export function validateElectiveWeightProfiles(expectedElectiveNames = []) {
  const errors = [];
  const profileNames = Object.keys(ELECTIVE_WEIGHT_PROFILES);

  expectedElectiveNames.forEach((electiveName) => {
    if (!getElectiveWeightProfile(electiveName)) {
      errors.push(`Missing weight profile for "${electiveName}".`);
    }
  });

  profileNames.forEach((electiveName) => {
    const profile = ELECTIVE_WEIGHT_PROFILES[electiveName];
    const aptitudeTotal = sumWeights(profile.aptitude);
    const riasecTotal = sumWeights(profile.riasec);

    if (Math.abs(aptitudeTotal - 1) > WEIGHT_TOLERANCE) {
      errors.push(`Aptitude weights for "${electiveName}" total ${aptitudeTotal.toFixed(4)} instead of 1.0000.`);
    }

    if (Math.abs(riasecTotal - 1) > WEIGHT_TOLERANCE) {
      errors.push(`RIASEC weights for "${electiveName}" total ${riasecTotal.toFixed(4)} instead of 1.0000.`);
    }
  });

  return errors;
}
